def configure_fonts() -> None:
    global REGULAR_PROP, SEMIBOLD_PROP

    for font_path in (REGULAR_FONT_PATH, SEMIBOLD_FONT_PATH):
        if font_path.exists():
            font_manager.fontManager.addfont(str(font_path))

    if REGULAR_FONT_PATH.exists() and SEMIBOLD_FONT_PATH.exists():
        regular_name = font_manager.FontProperties(fname=str(REGULAR_FONT_PATH)).get_name()
        REGULAR_PROP = FontProperties(fname=str(REGULAR_FONT_PATH), size=9)
        SEMIBOLD_PROP = FontProperties(fname=str(SEMIBOLD_FONT_PATH), size=9)
        sans_serif = [regular_name, "DejaVu Sans"]
    else:
        regular_name = "DejaVu Sans"
        REGULAR_PROP = FontProperties(family=regular_name, size=9)
        SEMIBOLD_PROP = FontProperties(family=regular_name, weight="semibold", size=9)
        sans_serif = [regular_name]

    plt.rcParams.update(
        {
            "font.family": regular_name,
            "font.sans-serif": sans_serif,
            "font.weight": "regular",
            "axes.labelweight": "regular",
            "axes.titleweight": "regular",
            "font.size": 9,
            "axes.labelsize": 9,
            "axes.titlesize": 9,
            "xtick.labelsize": 9,
            "ytick.labelsize": 9,
            "legend.fontsize": 7,
            "pdf.fonttype": 42,
            "ps.fonttype": 42,
            "axes.linewidth": 0.8,
            "hatch.linewidth": 0.35,
        }
    )


def apply_axis_fonts(ax: plt.Axes) -> None:
    if REGULAR_PROP is None:
        return
    for label in ax.get_xticklabels() + ax.get_yticklabels():
        label.set_fontproperties(REGULAR_PROP)


def load_compute_cdf() -> list[tuple[float, float]]:
    points: list[tuple[float, float]] = []
    with COMPUTE_CDF_PATH.open(newline="") as handle:
        for row in csv.DictReader(handle):
            points.append((float(row["value_us"]), float(row["cdf"])))
    return sorted(points)


def style_cdf_axis(ax: plt.Axes, *, show_ylabel: bool) -> None:
    if show_ylabel:
        ax.set_ylabel("CDF", rotation=270, labelpad=8)
    ax.yaxis.tick_right()
    ax.yaxis.set_label_position("right")
    ax.tick_params(labelleft=False, labelright=True, length=3.0, width=0.8, pad=1)
    ax.set_ylim(0, 1.02)
    ax.set_yticks([0, 0.5, 1.0])
    ax.grid(True, which="major", axis="both", linestyle=(0, (1, 7)), linewidth=0.7, color="black", alpha=0.75)
    ax.margins(x=0.04, y=0.02)
    apply_axis_fonts(ax)


def plot_line(ax: plt.Axes, series: PlotSeries) -> None:
    points = sorted(series.points)
    latency_ms = [point[0] for point in points]
    cdf = [point[1] for point in points]
    ax.plot(
        latency_ms,
        cdf,
        label=series.label,
        color=series.color,
        marker=series.marker,
        markersize=2.4,
        markevery=20,
        linewidth=series.linewidth,
    )


def build_series() -> list[PlotSeries]:
    return [
        PlotSeries("GustANN", GUSTANN_IO_CDF, "#2ca02c", "^"),
        PlotSeries("FlashANNS", FLASHANNS_IO_CDF, "#ff7f0e", "s"),
        PlotSeries("GPipeANN\n(ours)", GPIPEANN_IO_CDF, "#1f77b4", "o", linewidth=1.6),
    ]


def draw_io_latency(ax: plt.Axes, *, show_ylabel: bool) -> None:
    for series in build_series():
        plot_line(ax, series)

    ax.set_xlabel("Per-hop I/O\nstall time (ms)", labelpad=0)
    ax.xaxis.set_major_formatter(FuncFormatter(lambda value, _: f"{value:g}"))
    style_cdf_axis(ax, show_ylabel=show_ylabel)
    if not show_ylabel:
        ax.tick_params(labelright=False)

    ax.text(0.08, 0.84, "(b)", transform=ax.transAxes, color="#8f3333", fontweight="semibold", va="bottom", ha="left", zorder=20)

    legend_prop = FontProperties(fname=str(REGULAR_FONT_PATH), size=8) if REGULAR_FONT_PATH.exists() else FontProperties(size=8)
    ax.legend(
        loc="lower right",
        frameon=False,
        borderpad=0.0,
        handlelength=1.3,
        handletextpad=0.35,
        labelspacing=0.2,
        prop=legend_prop,
    )


def draw_compute_cdf(ax: plt.Axes, *, show_ylabel: bool) -> None:
    points = [(0.0, 0.0), *load_compute_cdf()]
    latency_us = [point[0] for point in points]
    cdf = [point[1] for point in points]
    ax.plot(
        latency_us,
        cdf,
        color="#1f77b4",
        marker="o",
        markersize=2.4,
        markevery=20,
        linewidth=1.6,
    )

    ax.set_xlabel("Per-hop computing\ntime ($\\mu$s)", labelpad=0)
    ax.xaxis.set_major_formatter(FuncFormatter(lambda value, _: f"{value:g}"))
    style_cdf_axis(ax, show_ylabel=show_ylabel)
    ax.set_xlim(0, latency_us[-1] * 1.04)

    ax.text(0.08, 0.84, "(c)", transform=ax.transAxes, color="#8f3333", fontweight="semibold", va="bottom", ha="left", zorder=20)


def draw_gpu_utilization(ax: plt.Axes) -> None:
    x = np.arange(len(GPU_SYSTEMS))
    bars = ax.bar(
        x,
        GPU_UTILIZATION,
        width=0.62,
        color=BAR_COLORS,
        edgecolor="black",
        linewidth=0.8,
    )
    for bar, hatch in zip(bars, BAR_HATCHES):
        bar.set_hatch(hatch)
    for bar, value in zip(bars, GPU_UTILIZATION):
        ax.text(
            bar.get_x() + bar.get_width() / 2,
            value + 1.8,
            f"{value}%",
            ha="center",
            va="bottom",
            fontproperties=SEMIBOLD_PROP,
            fontsize=8,
            color="#8f3333",
        )

    title = ax.set_title(
        "(a)",
        loc="left",
        color="#8f3333",
        fontweight="semibold",
        y=0.84,
        pad=0,
    )
    title.set_zorder(20)

    ax.set_xticks(x)
    ax.set_xticklabels(GPU_SYSTEMS, rotation=90, ha="center", va="top")
    ax.set_ylabel("Utilization", rotation=90, labelpad=2)
    ax.yaxis.tick_left()
    ax.yaxis.set_label_position("left")
    ax.set_ylim(0, 120)
    ax.set_yticks([0, 50, 100])
    ax.yaxis.set_major_formatter(FuncFormatter(lambda value, _: f"{value:g}%" if value <= 100 else ""))
    ax.grid(True, axis="y", linestyle=(0, (1, 7)), linewidth=0.7, color="black", alpha=0.75)
    ax.tick_params(length=3.0, width=0.8, pad=1)
    apply_axis_fonts(ax)


def save_plot() -> None:
    configure_fonts()
    fig = plt.figure(figsize=(3.5, 1.5))
    gs = gridspec.GridSpec(1, 4, figure=fig, width_ratios=[2.9, 0.15, 4.0, 2.0], wspace=0.16)
    ax_gpu = fig.add_subplot(gs[0, 0])
    ax_io = fig.add_subplot(gs[0, 2])
    ax_compute = fig.add_subplot(gs[0, 3], sharey=ax_io)

    draw_gpu_utilization(ax_gpu)
    draw_io_latency(ax_io, show_ylabel=False)
    draw_compute_cdf(ax_compute, show_ylabel=True)

    fig.subplots_adjust(left=0.16, right=0.88, bottom=0.45, top=0.96)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(OUTPUT)
    plt.close(fig)
    print(f"saved: {OUTPUT}")


def main() -> None:
    save_plot()


if __name__ == "__main__":
    main()
